import apiClient from '../config';
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//GET ALL POST
export const handleGetAllPosts = async () => {
  const response = await apiClient.get('/post');
  return response.data;
};

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//GET SINGLE POST
export const handleGetSinglePost = async (id: string) => {
  const response = await apiClient.get(`/post/${id}`);
  return response;
};

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//GET POST BY GENRE
export const handleGetPostByGenre = async (genre: string) => {
  const response = await apiClient.get(`/post/genre/${genre}`);
  return response;
};

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//GET ALL POST BY GENRE
export const handleGetAllPostsByGenre = async () => {
  const response = await apiClient.get('/post/genre');
  return response;
};

export const getAllChannel = async () => {
  const response = await apiClient.get('/channel');
  return response;
};

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
//GET ALL WATCHED VIDEOS
export const handleGetMyWatchList = async () => {
  const response = await apiClient.get('/post/watched/all');
  return response.data;
};

/////////////////////////////////////////////////////////////////////////////////////////////////
//ADD TO WATCHED VIDEOS
export const handleAddView = async ({ postId }: { postId: string }) => {
  const response = await apiClient.post(`/views/${postId}`);
  return response;
};
